IF (SELECT COUNT_BIG(*) FROM #snes_catalog) <> 1749
    THROW 50002, 'The SNES catalog is incomplete.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    UPDATE target
    SET
        [release_date] = source.[release_date],
        [publisher] = source.[publisher]
    FROM [dbo].[videogame] AS target
    INNER JOIN #snes_catalog AS source
        ON CONVERT(nvarchar(500), target.[name]) = source.[name];

    INSERT INTO [dbo].[videogame] ([name], [release_date], [publisher])
    SELECT source.[name], source.[release_date], source.[publisher]
    FROM #snes_catalog AS source
    WHERE NOT EXISTS
    (
        SELECT 1
        FROM [dbo].[videogame] AS target WITH (UPDLOCK, HOLDLOCK)
        WHERE CONVERT(nvarchar(500), target.[name]) = source.[name]
    );

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0
        ROLLBACK TRANSACTION;
    THROW;
END CATCH;

SELECT
    COUNT_BIG(*) AS [catalog_rows],
    MIN([release_date]) AS [first_release],
    MAX([release_date]) AS [last_release]
FROM #snes_catalog;
